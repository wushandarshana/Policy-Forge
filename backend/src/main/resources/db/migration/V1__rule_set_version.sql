-- Append-only store of versioned product rule sets (NFR-05). A new version is a new row; rows are never updated.
-- rules_json holds the published JSON exactly as stored (byte for byte). The money columns are denormalised copies of
-- values inside it, kept NUMERIC so no floating-point type ever touches money (NFR-01).
CREATE TABLE rule_set_version (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code     VARCHAR(50)  NOT NULL,
    version          INT          NOT NULL,
    product_name     VARCHAR(200) NOT NULL,
    rating_model     VARCHAR(30)  NOT NULL,
    effective_from   DATE         NOT NULL,
    sum_insured_min  NUMERIC(19,2) NOT NULL,
    sum_insured_max  NUMERIC(19,2) NOT NULL,
    cancellation_fee NUMERIC(19,2) NOT NULL,
    rules_json       CLOB         NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by       VARCHAR(100) NOT NULL,
    CONSTRAINT uq_rule_set_version UNIQUE (product_code, version),
    CONSTRAINT ck_rule_set_version_number CHECK (version >= 1)
);
