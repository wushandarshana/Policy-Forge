-- Endorsements (AC-06, NFR-02). An endorsement is an immutable record of one mid-term change to an in-force policy: the
-- type, the normalised payload, the version before and after, the re-rated premium and the pro-rata adjustment. A new
-- fact is a new row: application code never updates or deletes one. It is written in the same transaction as the new
-- policy_version and the policy's ENDORSED transition (AC-06.3).
-- sequence_no is unique per policy and starts at 1. Two concurrent endorsements of one policy compute the same next
-- sequence_no, so the unique key makes the second insert fail, and the service answers 409 POLICY_UPDATE_CONFLICT.
-- Money columns are NUMERIC(19,2) (NFR-01). payload_json holds the address or the nominee of the request and is personal
-- data: it is never logged (NFR-03).
CREATE TABLE endorsement (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_number      VARCHAR(20)   NOT NULL,
    sequence_no        INT           NOT NULL,
    type               VARCHAR(30)   NOT NULL,
    payload_json       CLOB          NOT NULL,
    before_version_no  INT           NOT NULL,
    after_version_no   INT           NOT NULL,
    new_annual_premium NUMERIC(19,2) NOT NULL,
    adjustment         NUMERIC(19,2) NOT NULL,
    effective_date     DATE          NOT NULL,
    actor_id           VARCHAR(100)  NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_endorsement_policy_sequence UNIQUE (policy_number, sequence_no),
    CONSTRAINT fk_endorsement_policy FOREIGN KEY (policy_number) REFERENCES policy (policy_number),
    CONSTRAINT ck_endorsement_type CHECK (type IN ('CHANGE_ADDRESS', 'ADD_NOMINEE', 'CHANGE_SUM_INSURED')),
    CONSTRAINT ck_endorsement_sequence_no CHECK (sequence_no >= 1),
    CONSTRAINT ck_endorsement_versions CHECK (before_version_no >= 1 AND after_version_no = before_version_no + 1)
);
