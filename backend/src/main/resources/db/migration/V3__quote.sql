-- Append-only store of quotes (NFR-02): a quote is immutable once priced. Rows are never updated or deleted.
-- Money columns are NUMERIC(19,2) (NFR-01). risk_inputs_json keeps the full risk inputs server-side, including health
-- inputs; the public read never returns them (NFR-04.2). breakdown_json holds the applied factors as decimal strings.
CREATE TABLE quote (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id         VARCHAR(40)   NOT NULL,
    product_code     VARCHAR(50)   NOT NULL,
    rule_version     INT           NOT NULL,
    sum_insured      NUMERIC(19,2) NOT NULL,
    annual_premium   NUMERIC(19,2) NOT NULL,
    breakdown_json   CLOB          NOT NULL,
    risk_inputs_json CLOB          NOT NULL,
    valid_until      DATE          NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_quote_quote_id UNIQUE (quote_id),
    CONSTRAINT fk_quote_rule_set_version FOREIGN KEY (product_code, rule_version)
        REFERENCES rule_set_version (product_code, version)
);
