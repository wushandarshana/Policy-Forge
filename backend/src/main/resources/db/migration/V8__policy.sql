-- Policy issuance (AC-05, AC-10, NFR-02). A policy is created when an APPROVED application is issued (policy-issuance
-- spec). The policy row is a mutable aggregate: only its status and current_version_no ever change, through the domain
-- state machine, guarded by the optimistic-lock column "version". Everything else is append-only: a policy_version is an
-- immutable snapshot (a new fact is a new row), a policy_status_transition records every status change and the policy's
-- status always equals the latest transition's to_status. policy_term changes only its paid flag.
-- One policy per application (unique application_id) and one number per policy (unique policy_number).
-- Money columns are NUMERIC(19,2) (NFR-01). risk_inputs_json keeps the full risk inputs of the quote, health inputs
-- included, for re-rating; the API returns an allow-listed view of it (NFR-04.2). address_* and nominees_json are
-- personal data and are never logged (NFR-03).
CREATE TABLE policy (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_number      VARCHAR(20)  NOT NULL,
    application_id     VARCHAR(40)  NOT NULL,
    product_code       VARCHAR(50)  NOT NULL,
    customer_id        VARCHAR(100) NOT NULL,
    status             VARCHAR(20)  NOT NULL,
    current_version_no INT          NOT NULL,
    version            BIGINT       NOT NULL,
    issued_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_policy_policy_number UNIQUE (policy_number),
    CONSTRAINT uq_policy_application_id UNIQUE (application_id),
    CONSTRAINT fk_policy_application FOREIGN KEY (application_id) REFERENCES application (application_id),
    CONSTRAINT ck_policy_status CHECK (status IN ('ACTIVE', 'ENDORSED', 'RENEWED', 'LAPSED', 'CANCELLED')),
    CONSTRAINT ck_policy_current_version_no CHECK (current_version_no >= 1)
);

CREATE INDEX ix_policy_customer ON policy (customer_id, issued_at);

-- Append-only snapshots of the policy: version 1 at issuance, one more for every endorsement.
CREATE TABLE policy_version (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_number     VARCHAR(20)   NOT NULL,
    version_no        INT           NOT NULL,
    sum_insured       NUMERIC(19,2) NOT NULL,
    annual_premium    NUMERIC(19,2) NOT NULL,
    risk_inputs_json  CLOB          NOT NULL,
    address_line1     VARCHAR(200)  NOT NULL,
    address_city      VARCHAR(100)  NOT NULL,
    address_postcode  VARCHAR(6)    NOT NULL,
    nominees_json     CLOB          NOT NULL,
    rule_version      INT           NOT NULL,
    effective_date    DATE          NOT NULL,
    expiry_date       DATE          NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_policy_version_policy_version UNIQUE (policy_number, version_no),
    CONSTRAINT fk_policy_version_policy FOREIGN KEY (policy_number) REFERENCES policy (policy_number),
    CONSTRAINT ck_policy_version_version_no CHECK (version_no >= 1)
);

-- One row per cover term: term 1 at issuance (paid), later terms at renewal. Only the paid flag can change.
CREATE TABLE policy_term (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_number VARCHAR(20)   NOT NULL,
    term_no       INT           NOT NULL,
    start_date    DATE          NOT NULL,
    end_date      DATE          NOT NULL,
    premium       NUMERIC(19,2) NOT NULL,
    paid          BOOLEAN       NOT NULL,
    CONSTRAINT uq_policy_term_policy_term UNIQUE (policy_number, term_no),
    CONSTRAINT fk_policy_term_policy FOREIGN KEY (policy_number) REFERENCES policy (policy_number),
    CONSTRAINT ck_policy_term_term_no CHECK (term_no >= 1)
);

-- Append-only status history (AC-10.4). from_status is NULL for the move that creates the policy (NULL to ACTIVE).
CREATE TABLE policy_status_transition (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_number VARCHAR(20)  NOT NULL,
    from_status   VARCHAR(20),
    to_status     VARCHAR(20)  NOT NULL,
    reason        VARCHAR(50)  NOT NULL,
    actor_id      VARCHAR(100) NOT NULL,
    occurred_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_policy_status_transition_policy FOREIGN KEY (policy_number) REFERENCES policy (policy_number),
    CONSTRAINT ck_policy_status_transition_from CHECK (from_status IS NULL
        OR from_status IN ('ACTIVE', 'ENDORSED', 'RENEWED', 'LAPSED', 'CANCELLED')),
    CONSTRAINT ck_policy_status_transition_to CHECK (to_status IN ('ACTIVE', 'ENDORSED', 'RENEWED', 'LAPSED', 'CANCELLED'))
);

CREATE INDEX ix_policy_status_transition_policy ON policy_status_transition (policy_number, id);

-- The per-product, per-issue-year counter behind the policy number (PF-<TL|MO|HH>-<YYYY>-<NNNNNN>). The issuing
-- transaction locks the row, increments last_value and commits with the policy, so a rolled-back issue gives its number
-- back and the numbers of one product and year stay contiguous. The unique key guarantees one counter per product-year.
CREATE TABLE policy_number_sequence (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_code VARCHAR(50) NOT NULL,
    seq_year     INT         NOT NULL,
    last_value   INT         NOT NULL,
    CONSTRAINT uq_policy_number_sequence UNIQUE (product_code, seq_year),
    CONSTRAINT ck_policy_number_sequence_last_value CHECK (last_value >= 0 AND last_value <= 999999)
);
