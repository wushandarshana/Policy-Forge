-- Cancellation refunds (AC-08, NFR-02). A refund record is the immutable account of one cancellation: the term it was
-- calculated on, the premium basis (the term premium plus the endorsement adjustments of that term), the day counts, the
-- cancellation fee, the refund amount and the formula string that shows the numbers. A new fact is a new row: application
-- code never updates or deletes one, and its repository has no such method. It is written in the same transaction as the
-- policy's CANCELLED transition (AC-08.4).
-- policy_number is unique: a policy is cancelled once, so it has at most one refund record. Two concurrent cancels both
-- insert for the same policy, so the unique key makes the second insert fail, and the service answers 409
-- POLICY_UPDATE_CONFLICT with nothing written.
-- Money columns are NUMERIC(19,2) (NFR-01). The checks are a last line of defence behind the domain calculator: a refund is
-- never negative (AC-08.3) and never more than the premium it was calculated on, and at least one day of the term is left
-- unexpired because the cancellation date lies inside the term. The formula holds only the numbers of the calculation.
CREATE TABLE refund_record (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_number     VARCHAR(20)   NOT NULL,
    term_no           INT           NOT NULL,
    cancellation_date DATE          NOT NULL,
    premium           NUMERIC(19,2) NOT NULL,
    term_days         INT           NOT NULL,
    unexpired_days    INT           NOT NULL,
    cooling_off       BOOLEAN       NOT NULL,
    fee               NUMERIC(19,2) NOT NULL,
    amount            NUMERIC(19,2) NOT NULL,
    formula           VARCHAR(200)  NOT NULL,
    actor_id          VARCHAR(100)  NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_refund_record_policy UNIQUE (policy_number),
    CONSTRAINT fk_refund_record_policy FOREIGN KEY (policy_number) REFERENCES policy (policy_number),
    CONSTRAINT ck_refund_record_term_no CHECK (term_no >= 1),
    CONSTRAINT ck_refund_record_days CHECK (term_days >= 1 AND unexpired_days >= 1 AND unexpired_days <= term_days),
    CONSTRAINT ck_refund_record_money CHECK (premium >= 0 AND fee >= 0 AND amount >= 0 AND amount <= premium)
);
