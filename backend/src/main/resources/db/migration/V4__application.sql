-- Applications (AC-03, underwriting spec U-3, U-4, U-9). One application per quote (unique quote_id). The status is the
-- only column that ever changes, through the domain transitions, guarded by the optimistic-lock column "version" (U-9).
-- The KYC columns hold the submitted details and are sized for the U-4 limits: Aadhaar 14 characters (XXXX-XXXX-1234),
-- PAN 10, postcode 6. They are never logged and never returned to the owner (NFR-03, U-7).
CREATE TABLE application (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id       VARCHAR(40)  NOT NULL,
    quote_id             VARCHAR(40)  NOT NULL,
    customer_id          VARCHAR(100) NOT NULL,
    product_code         VARCHAR(50)  NOT NULL,
    status               VARCHAR(20)  NOT NULL,
    version              BIGINT       NOT NULL,
    kyc_full_name        VARCHAR(200) NOT NULL,
    kyc_date_of_birth    DATE         NOT NULL,
    kyc_aadhaar          VARCHAR(14)  NOT NULL,
    kyc_pan              VARCHAR(10)  NOT NULL,
    kyc_address_line1    VARCHAR(200) NOT NULL,
    kyc_address_city     VARCHAR(100) NOT NULL,
    kyc_address_postcode VARCHAR(6)   NOT NULL,
    submitted_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_application_application_id UNIQUE (application_id),
    CONSTRAINT uq_application_quote_id UNIQUE (quote_id),
    CONSTRAINT fk_application_quote FOREIGN KEY (quote_id) REFERENCES quote (quote_id),
    CONSTRAINT ck_application_status CHECK (status IN ('SUBMITTED', 'UNDERWRITING', 'APPROVED', 'REFERRED', 'DECLINED', 'ISSUED'))
);

CREATE INDEX ix_application_customer ON application (customer_id, submitted_at);
CREATE INDEX ix_application_status ON application (status, submitted_at);
