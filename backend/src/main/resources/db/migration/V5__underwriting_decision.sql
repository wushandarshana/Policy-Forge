-- Append-only underwriting decisions (NFR-02, underwriting spec U-9). source is RULES (the automated evaluation, actor
-- "system"), MANUAL or OVERRIDE. Each row keeps the outcome, the reason codes (sorted, comma separated) with their
-- descriptions as JSON, the rule version, the actor, the comment and the time. Rows are never updated or deleted.
CREATE TABLE underwriting_decision (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id VARCHAR(40)  NOT NULL,
    source         VARCHAR(10)  NOT NULL,
    outcome        VARCHAR(20)  NOT NULL,
    reason_codes   VARCHAR(500) NOT NULL,
    reasons_json   CLOB         NOT NULL,
    rule_version   INT          NOT NULL,
    actor_id       VARCHAR(100) NOT NULL,
    comment_text   VARCHAR(2000),
    decided_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_underwriting_decision_application FOREIGN KEY (application_id) REFERENCES application (application_id),
    CONSTRAINT ck_underwriting_decision_source CHECK (source IN ('RULES', 'MANUAL', 'OVERRIDE'))
);

CREATE INDEX ix_underwriting_decision_application ON underwriting_decision (application_id, id);
