package com.horizon.policyforge.domain.cancellation;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;

/**
 * AC-08.5, the oracle cross-check: the property test next to this one proves invariants (a refund stays within the
 * premium), and this test proves the numbers. The fixture {@code oracle/ac-08-5-refund-cases.csv} is generated by
 * {@code scripts/gen_refund_oracle_cases.py} from {@code refund()} in the premium-calc-evaluator oracle
 * ({@code premium_check.py}): exact decimal arithmetic in another language, so no expected value here comes from
 * production code. {@code gen_refund_oracle_cases.py --check} (a quality gate) keeps the file equal to a fresh
 * generation, so it cannot be edited by hand.
 *
 * <p>Row layout: {@code case,termStart,termEnd,cancellationDate,firstTerm,coolingOffDays,premium,fee,termDays,
 * unexpiredDays,coolingOff,amount}. The policy effective date is the term start, and money is a decimal string of
 * scale 2.
 */
@Tag("AC-08")
class ProRataRefundOracleCrossCheckTest {

    private static final String FIXTURE = "/oracle/ac-08-5-refund-cases.csv";
    private static final String HEADER = "case,termStart,termEnd,cancellationDate,firstTerm,coolingOffDays,premium,fee,"
            + "termDays,unexpiredDays,coolingOff,amount";
    private static final int CASES = 1000;

    /** One fixture row, every field as the oracle wrote it. */
    private record OracleCase(int line, String name, LocalDate termStart, LocalDate termEnd, LocalDate cancellationDate,
            boolean firstTerm, int coolingOffDays, String premium, String fee, int termDays, int unexpiredDays,
            boolean coolingOff, String amount) {

        static OracleCase parse(int line, String text) {
            String[] f = text.split(",", -1);
            assertThat(f).as("line " + line + " has the 12 columns of the header").hasSize(12);
            return new OracleCase(line, f[0], LocalDate.parse(f[1]), LocalDate.parse(f[2]), LocalDate.parse(f[3]),
                    Boolean.parseBoolean(f[4]), Integer.parseInt(f[5]), f[6], f[7], Integer.parseInt(f[8]),
                    Integer.parseInt(f[9]), Boolean.parseBoolean(f[10]), f[11]);
        }

        String context() {
            return "line " + line + " " + name + " premium=" + premium + " fee=" + fee + " " + termStart + ".."
                    + termEnd + " cancel=" + cancellationDate + " firstTerm=" + firstTerm + " coolingOffDays="
                    + coolingOffDays;
        }
    }

    private static List<OracleCase> fixture() throws IOException {
        try (InputStream in = ProRataRefundOracleCrossCheckTest.class.getResourceAsStream(FIXTURE)) {
            assertThat(in).as("the oracle fixture " + FIXTURE + " is on the test classpath").isNotNull();
            BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            assertThat(reader.readLine()).as("the fixture header").isEqualTo(HEADER);
            List<OracleCase> cases = new ArrayList<>();
            String text;
            int line = 1;
            while ((text = reader.readLine()) != null) {
                line++;
                cases.add(OracleCase.parse(line, text));
            }
            return cases;
        }
    }

    @Test
    @Tag("AC-08.5")
    @DisplayName("AC-08.5: the production calculator equals the premium_check.py oracle on 1,000 generated cases")
    void theCalculatorEqualsTheOracleOnEveryGeneratedCase() throws IOException {
        List<OracleCase> cases = fixture();
        ProRataRefundCalculator calculator = new ProRataRefundCalculator();

        assertThat(cases).as("the fixture has 1,000 data rows").hasSize(CASES);
        for (OracleCase row : cases) {
            RefundQuote quote = calculator.calculate(new BigDecimal(row.premium()), row.termStart(), row.termEnd(),
                    row.cancellationDate(), row.termStart(), row.firstTerm(), row.coolingOffDays(),
                    new BigDecimal(row.fee()));

            String context = row.context();
            assertThat(quote.amount().scale()).as("amount scale, " + context).isEqualTo(2);
            assertThat(quote.amount().toPlainString()).as("amount, " + context).isEqualTo(row.amount());
            assertThat(quote.termDays()).as("termDays, " + context).isEqualTo(row.termDays());
            assertThat(quote.unexpiredDays()).as("unexpiredDays, " + context).isEqualTo(row.unexpiredDays());
            assertThat(quote.coolingOff()).as("coolingOff, " + context).isEqualTo(row.coolingOff());
            assertThat(quote.fee().scale()).as("fee scale, " + context).isEqualTo(2);
            assertThat(quote.fee().toPlainString()).as("fee, " + context)
                    .isEqualTo(row.coolingOff() ? "0.00" : row.fee());
        }

        assertThat(cases.stream().filter(OracleCase::coolingOff).count()).as("cooling-off rows").isPositive();
        assertThat(cases.stream().filter(row -> !row.firstTerm()).count()).as("renewal-term rows").isPositive();
        assertThat(cases.stream().filter(row -> !row.coolingOff() && "0.00".equals(row.amount())).count())
                .as("rows whose pro-rata share is floored at 0.00").isPositive();
    }
}
